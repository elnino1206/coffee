#!/usr/bin/env bash
# Сборка сайта под выкладку на домен.
#
# Копирует рабочую версию в dist/ — то, что уезжает на хостинг.
# Скриптом, а не руками: копия, которую правят напрямую, за неделю
# разъезжается с исходником, и потом никто не помнит, где правда.
# Правда — в versions/v2-anim, dist пересобирается из него.
#
# Выдача лежит в dist/, а не в aljar.ru/, как было раньше: в aljar.ru/
# теперь Laravel-приложение, а сборка начинается с полного удаления
# папки выдачи.
#
# Запуск из корня проекта:  bash build.sh

set -euo pipefail

SRC="versions/v2-anim"
OUT="dist"

if [ ! -d "$SRC" ]; then
  echo "Нет исходника: $SRC" >&2
  exit 1
fi

# Полная пересборка: файл, удалённый в исходнике, не должен пережить
# сборку в выдаче.
rm -rf "$OUT"
mkdir -p "$OUT"
cp -r "$SRC"/. "$OUT"/

# Служебное в выдаче не нужно
rm -f "$OUT/admin/README.md"

FILES=$(find "$OUT" -type f | wc -l | tr -d ' ')
SIZE=$(du -sh "$OUT" | cut -f1)

cat > "$OUT/BUILD.txt" <<EOF
Статическая сборка сайта Al Jar Coffee

Собрано:    $(date '+%Y-%m-%d %H:%M')
Источник:   $SRC
Файлов:     $FILES
Объём:      $SIZE

Эта папка создаётся скриптом build.sh и перезаписывается целиком.
Править здесь нечего — правки делаются в $SRC и пересобираются.

Перед выкладкой:
  - админка (/admin/) должна быть закрыта авторизацией на стороне
    сервера; страницы помечены noindex, но это не защита;
  - настроить заголовки кеширования: HTML без кеша, CSS/JS и картинки
    надолго — у них в адресе есть версия.
EOF

echo "Собрано в $OUT — $FILES файлов, $SIZE"
